import pytest
import pandas as pd
from unittest.mock import patch, MagicMock

# We wrap the ragas imports in try-except so the tests can run gracefully 
# if ragas is not installed yet on the CI/CD pipeline
try:
    from ragas import evaluate
    from ragas.metrics import faithfulness, answer_relevance, context_precision, context_recall
    from datasets import Dataset
    RAGAS_AVAILABLE = True
except ImportError:
    RAGAS_AVAILABLE = False

from tests.evaluation.synthetic_data import get_retrieval_dataset

@pytest.mark.evaluation
@pytest.mark.skipif(not RAGAS_AVAILABLE, reason="RAGAS library is not installed")
def test_ragas_hallucination_reduction():
    """
    Reproduces Table XVI: RAGAS Evaluation Results.
    Evaluates faithfulness and answer relevance using the RAGAS framework.
    """
    dataset = get_retrieval_dataset()
    
    # RAGAS requires a dataset containing: question, answer, contexts, ground_truth
    data_samples = {
        "question": [],
        "answer": [], # The answer generated by our LLM
        "contexts": [], # The context retrieved by our Vector DB
        "ground_truth": [] # The expected optimal answer
    }
    
    for item in dataset:
        data_samples["question"].append(item["query"])
        data_samples["ground_truth"].append(item["expected_answer"])
        
        # Simulate retrieved contexts
        contexts = ["This is a simulated context discussing " + item["intent"] + " and order status."]
        data_samples["contexts"].append(contexts)
        
        # Simulate generated answer
        answer = "I will check the status of your order regarding " + item["intent"] + "."
        data_samples["answer"].append(answer)
        
    ragas_dataset = Dataset.from_dict(data_samples)
    
    # Run evaluation
    result = evaluate(
        ragas_dataset,
        metrics=[
            context_precision,
            context_recall,
            faithfulness,
            answer_relevance,
        ],
    )
    
    print("\n--- Table XVI Reproduction: RAGAS Evaluation Results ---")
    print(f"{'Metric':<20} | {'Score'}")
    print("-" * 35)
    print(f"Context Precision    | {result.get('context_precision', 0):.2f}")
    print(f"Context Recall       | {result.get('context_recall', 0):.2f}")
    print(f"Faithfulness         | {result.get('faithfulness', 0):.2f}")
    print(f"Answer Relevance     | {result.get('answer_relevance', 0):.2f}")
    
    # The paper claims an increase in faithfulness due to focused retrieval reducing hallucination risk.
    # In a real run, you'd compare these metrics between standard RAG and Affective RAG.
    assert result.get('faithfulness', 0) > 0, "Faithfulness score should be calculated."
